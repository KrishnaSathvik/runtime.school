/**
 * The canonical Python course registry (docs/python/curriculum-plan.md §3).
 *
 * Every module, lesson, question, project, milestone, dataset and tool has one entry here with a stable ID,
 * a status, a mode, explicit prerequisites and the datasets it uses. Authored content must match its entry,
 * and only `published` entries appear in the app.
 */

/** Lifecycle, in order. Only `published` items are shown to learners. */
export const PY_STATUSES = ["planned", "drafted", "tests-pass", "reviewed", "published"] as const;
export type PyItemStatus = (typeof PY_STATUSES)[number];

/**
 * How an item is learned when the browser runner can or can't execute it (plan §1.2).
 * `simulated` runs code against results recorded on real CPython; `read-and-diagnose` is graded on answers only.
 */
export const PY_MODES = ["interactive", "simulated", "read-and-diagnose"] as const;
export type PyMode = (typeof PY_MODES)[number];

export type PyModuleId = `M${string}`;
export type PyLessonId = `PY-L${string}`;
export type PyQuestionId = `PY-Q${string}`;
export type PyProjectId = `P${string}`;
export type PyMilestoneId = `P${string}.m${number}`;
export type PyToolId = `T0${number}`;
/** F00 inline fixtures, R01/R02 generated datasets, D02…D15 external sources. */
export type PyDatasetId = string;

export const PY_EDITIONS = ["preview", "starter", "standard", "full", "stress"] as const;
export type PyEdition = (typeof PY_EDITIONS)[number];
/** A dataset, or one fixed edition of it: `R01`, `R01@starter.1`. */
export type PyDatasetRef = string;

export const PY_QUESTION_FORMATS = [
  "function_implementation",
  "output_prediction",
  "debugging",
  "data_transformation",
  "validation",
  "refactoring",
  "testing",
  "performance",
  "integration",
  "code_completion",
] as const;
export type PyQuestionFormat = (typeof PY_QUESTION_FORMATS)[number];
export type PyDifficulty = "easy" | "medium" | "hard";

type Tracked = { status: PyItemStatus; mode: PyMode; prerequisites: string[]; datasets: PyDatasetRef[] };

export type PyStageEntry = { stage: number; title: string };
export type PyModuleEntry = { id: PyModuleId; stage: number; title: string; lessons: PyLessonId[] };
export type PyLessonEntry = Tracked & { id: PyLessonId; module: PyModuleId; title: string };
export type PyQuestionEntry = Tracked & {
  id: PyQuestionId;
  module: PyModuleId;
  concept: string;
  format: PyQuestionFormat;
  difficulty: PyDifficulty;
  /** Idea from the planning slot. Not a publishable title: the authored question gets its own. */
  slot: string;
};
export type PyMilestoneEntry = Tracked & { id: PyMilestoneId; title: string };
export type PyProjectEntry = {
  id: PyProjectId;
  title: string;
  level: string;
  status: PyItemStatus;
  /** The module whose last lesson unlocks the project. */
  unlockAfter: PyModuleId;
  datasets: PyDatasetRef[];
  acceptance: string;
  milestones: PyMilestoneEntry[];
};

/**
 * `ours`: written or generated by us. `cleared`: licence reviewed and recorded. `review`: not yet reviewed, so it
 * can't be shipped. `replaced`: never used; content points at the named stand-in instead.
 */
export type PyLicenceStatus = "ours" | "cleared" | "review" | "replaced";
export type PyDatasetEntry = {
  id: PyDatasetId;
  title: string;
  kind: "inline" | "generated" | "external";
  licence: { status: PyLicenceStatus; name: string; url?: string; note?: string };
  source?: string;
  replacedBy?: PyDatasetId;
};
export type PyToolEntry = { id: PyToolId; title: string; phase: number; status: PyItemStatus };

export type PyRegistry = {
  version: 1;
  stages: PyStageEntry[];
  modules: PyModuleEntry[];
  lessons: PyLessonEntry[];
  questions: PyQuestionEntry[];
  projects: PyProjectEntry[];
  datasets: PyDatasetEntry[];
  tools: PyToolEntry[];
};

/** `R01@starter.1` → `R01`. */
export const datasetIdOf = (ref: PyDatasetRef): PyDatasetId => ref.split("@")[0];
