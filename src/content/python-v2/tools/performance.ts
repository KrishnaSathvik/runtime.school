export const experimentById = (id: string | null | undefined) => EXPERIMENTS.find((e) => e.id === id);

/** Python lines that set each input variable, for the chosen option of each parameter. */
export function paramLines(e: PyExperiment, chosen: Record<string, number>): string {
  return e.params.map((p) => {
    const o = p.options[Math.max(0, Math.min(p.options.length - 1, chosen[p.name] ?? p.start))];
    return `${p.name} = ${typeof o.value === "number" ? o.value : JSON.stringify(o.value)}`;
  }).join("\n");
}
