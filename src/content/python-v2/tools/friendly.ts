/** Edition → size shown to learners. Editions not listed (preview, stress) aren't offered in the tools. */
export const SIZES: Record<string, string> = { starter: "Small", standard: "Medium", full: "Large" };
export const DEFAULT_SIZE = "starter";

export type ToolDataset = Friendly & { id: string; manifest: PyManifest; tables: string[] };

export const toolDatasets: ToolDataset[] = Object.values(pyManifests)
  .filter((m) => FRIENDLY[m.id])
  .map((m) => ({ ...FRIENDLY[m.id], id: m.id, manifest: m, tables: Object.keys(m.tables) }));

export const toolDataset = (id: string | null | undefined) => toolDatasets.find((d) => d.id === id) ?? null;

/** "order_items" → "Order items". */
export const tableLabel = (t: string) => (t.charAt(0).toUpperCase() + t.slice(1)).replace(/_/g, " ");

/** Sizes a dataset has, with the main table's row count: "Small · 300 orders". */
export function sizesOf(d: ToolDataset) {
  return Object.keys(SIZES)
    .filter((s) => d.manifest.editions[s]?.files)
    .map((s) => {
      const f = d.manifest.editions[s].files!.find((x) => x.layer === "clean" && x.table === d.start && (x.format ?? "csv") === "csv");
      return { size: s, label: SIZES[s], rows: f?.rows ?? 0, ref: d.manifest.editions[s].ref, unit: d.unit };
    });
}

/** The clean CSV files of one size, as the program sees them (data/orders.csv …). */
export function cleanFiles(d: ToolDataset, size = DEFAULT_SIZE) {
  return (d.manifest.editions[size]?.files ?? []).filter((f) => f.layer === "clean" && (f.format ?? "csv") === "csv");
}

/** Every file of one size: tables in every format, nested JSON, API pages, and the messy raw exports. */
export function allFiles(d: ToolDataset, size = DEFAULT_SIZE): PyEditionFile[] {
  return d.manifest.editions[size]?.files ?? [];
}

/** The sizes a dataset actually has, falling back to the nearest one it does have. */
export function sizeFor(d: ToolDataset, wanted: string): string {
  if (d.manifest.editions[wanted]?.files) return wanted;
  return ["starter", "standard", "full"].find((s) => d.manifest.editions[s]?.files) ?? "starter";
}

const FORMAT_LABEL: Record<string, string> = { csv: "CSV", json: "JSON", jsonl: "JSON Lines", geojson: "GeoJSON", parquet: "Parquet", text: "Text", sqlite: "SQLite" };
export const formatLabel = (f: PyEditionFile) => (f.path.endsWith(".xml") ? "XML" : FORMAT_LABEL[f.format ?? "csv"] ?? "File");

export function formatBytes(n: number): string {
  if (n >= 1e6) return `${(n / 1e6).toFixed(1)} MB`;
  if (n >= 1e3) return `${Math.round(n / 1e3)} KB`;
  return `${n} B`;
}

/**
 * Code that loads one file, in the most natural library for its format. Every snippet runs as written in the
 * Playground (tests/python-datasets.test.ts runs one for every format of every dataset).
 */
export function loadSnippet(f: PyEditionFile, style: "pandas" | "plain" = "pandas"): string {
  const p = `data/${f.path}`;
  const fmt = f.path.endsWith(".xml") ? "xml" : f.format ?? "csv";
  if (fmt === "csv")
    return style === "pandas"
      ? `import pandas as pd\n\ndf = pd.read_csv("${p}")\nprint(df.shape)\ndisplay(df.head())\n`
      : `import csv\n\nwith open("${p}", newline="", encoding="utf-8") as f:\n    rows = list(csv.DictReader(f))\n\nprint(len(rows), "rows")\nprint(rows[0])\n`;
  if (fmt === "parquet") return `import pandas as pd\n\n# Parquet keeps column types (dates, integers) that CSV loses.\ndf = pd.read_parquet("${p}")\nprint(df.dtypes)\ndisplay(df.head())\n`;
  if (fmt === "jsonl") return `import json\n\nrecords = []\nwith open("${p}", encoding="utf-8") as f:\n    for line in f:\n        records.append(json.loads(line))\n\nprint(len(records), "records")\nprint(sorted(records[0].keys()))\n`;
  if (fmt === "geojson") return `import json\n\nwith open("${p}", encoding="utf-8") as f:\n    collection = json.load(f)\n\nfeatures = collection["features"]\nprint(len(features), "features")\nfirst = features[0]\nprint(first["geometry"]["coordinates"])\nprint(first["properties"])\n`;
  if (fmt === "json") return `import json\n\nwith open("${p}", encoding="utf-8") as f:\n    data = json.load(f)\n\nprint(type(data).__name__)\nprint(list(data)[:10] if isinstance(data, dict) else len(data))\n`;
  if (fmt === "xml") return `import xml.etree.ElementTree as ET\n\nroot = ET.parse("${p}").getroot()\nrows = root.findall("row")\nprint(len(rows), "rows")\nprint(rows[0].attrib)\n`;
  return `with open("${p}", encoding="utf-8") as f:\n    print(f.read(500))\n`;
}

