/** R01 Runtime Market: tables, data dictionary, keys and editions. Rows come from generate.mjs. */
import { generateMarket, R01_SEED } from './generate.mjs';
import { makeRaw, RAW_ISSUES } from './raw.mjs';
import { cutEdition } from './editions.mjs';

const col = (name, type, description, nullable = false) => ({ name, type, description, nullable });

const dataset = {
  id: 'R01',
  title: 'Runtime Market',
  version: 1,
  seed: R01_SEED,
  description:
    'A fictional US online marketplace over two years (2024–2025): customers, sellers, products, orders, order lines, ' +
    'payments and reviews. Generated by Runtime with realistic seasonality, repeat buyers, price changes, cancellations, ' +
    'returns, refunds and late deliveries. Every name and email is invented.',
  licence: { name: 'Runtime-owned synthetic data', status: 'ours' },
  window: ['2024-01-01', '2025-12-31'],
  parquet: { tables: ['orders', 'order_items'] },
  tables: {
    customers: {
      description: 'One row per customer account. Some customers never ordered.',
      primaryKey: ['customer_id'],
      columns: [
        col('customer_id', 'text', 'C + 5 digits'),
        col('first_name', 'text', 'Invented first name'),
        col('last_name', 'text', 'Invented last name'),
        col('email', 'text', 'Unique, lowercase in the clean table'),
        col('city', 'text', 'Profile city; empty when the customer never filled it in', true),
        col('state', 'text', 'Two-letter US state'),
        col('segment', 'text', 'consumer or business'),
        col('signup_at', 'timestamp', 'Account creation, UTC (YYYY-MM-DD HH:MM:SS). Some accounts predate 2024'),
        col('marketing_opt_in', 'boolean', 'Agreed to marketing email'),
      ],
    },
    sellers: {
      description: 'Marketplace sellers who list products.',
      primaryKey: ['seller_id'],
      columns: [
        col('seller_id', 'text', 'S + 3 digits'), col('name', 'text', 'Store name'), col('city', 'text', 'Seller city'),
        col('state', 'text', 'Two-letter US state'), col('joined_on', 'date', 'Date the seller joined'),
        col('tier', 'text', 'standard, plus or enterprise'),
      ],
    },
    products: {
      description: 'The catalogue. Products can launch during the period or be discontinued.',
      primaryKey: ['product_id'],
      foreignKeys: [{ column: 'seller_id', references: 'sellers.seller_id' }],
      columns: [
        col('product_id', 'text', 'P + 4 digits'), col('sku', 'text', 'Stock code (SKU)'), col('name', 'text', 'Product name'),
        col('category', 'text', 'One of 8 categories'), col('subcategory', 'text', 'Subcategory within the category'),
        col('seller_id', 'text', 'Seller who lists it'), col('list_price', 'decimal', 'Current shelf price in USD; order lines record the price paid'),
        col('weight_kg', 'decimal', 'Shipping weight; missing for some products', true),
        col('launched_on', 'date', 'First day the product could be ordered'),
        col('discontinued_on', 'date', 'Last listing date; empty if still sold', true),
      ],
    },
    orders: {
      description: 'One row per order. Totals are subtotal + shipping_fee + tax.',
      primaryKey: ['order_id'],
      foreignKeys: [{ column: 'customer_id', references: 'customers.customer_id' }],
      columns: [
        col('order_id', 'text', 'O + 6 digits. Increases day by day, but not by time within a day: sort by ordered_at for time order'), col('customer_id', 'text', 'Who ordered'),
        col('ordered_at', 'timestamp', 'Order time, UTC'), col('channel', 'text', 'web, app, phone or marketplace'),
        col('status', 'text', 'processing, shipped, delivered, cancelled or returned (as of 2025-12-31)'),
        col('promo_code', 'text', 'Promotion applied, if any', true),
        col('subtotal', 'decimal', 'Sum of line totals after discount'), col('shipping_fee', 'decimal', '0 at $50+ or with FREESHIP, else 5.99'),
        col('tax', 'decimal', '7% of subtotal'), col('total', 'decimal', 'Amount charged'),
        col('ship_city', 'text', 'Delivery city'), col('ship_state', 'text', 'Delivery state'),
        col('shipped_at', 'timestamp', 'Empty for processing and cancelled orders', true),
        col('delivered_at', 'timestamp', 'Empty until delivered', true),
        col('estimated_delivery', 'date', 'Promised delivery date (order date + 6 days)'),
      ],
    },
    order_items: {
      description: 'Order lines. unit_price is the price at order time, which can differ from today\'s list_price.',
      primaryKey: ['order_id', 'line_no'],
      foreignKeys: [{ column: 'order_id', references: 'orders.order_id' }, { column: 'product_id', references: 'products.product_id' }],
      columns: [
        col('order_id', 'text', 'Order'), col('line_no', 'integer', 'Line number in the order, starting at 1'),
        col('product_id', 'text', 'Product'), col('quantity', 'integer', 'Units ordered'),
        col('unit_price', 'decimal', 'Price per unit when ordered'), col('discount_rate', 'decimal', 'Promotion discount, 0–0.25'),
        col('line_total', 'decimal', 'quantity × unit_price × (1 − discount_rate), rounded to cents'),
      ],
    },
    payments: {
      description: 'Payment events. An order can have a failed attempt, a split gift-card payment, a cancelled card hold or a refund (negative amount).',
      primaryKey: ['payment_id'],
      foreignKeys: [{ column: 'order_id', references: 'orders.order_id' }],
      columns: [
        col('payment_id', 'text', 'PAY + 7 digits'), col('order_id', 'text', 'Order'), col('attempt', 'integer', 'Attempt number within the order'),
        col('method', 'text', 'card, paypal, apple_pay, gift_card or bank_transfer'),
        col('status', 'text', 'captured, failed, voided or refunded'), col('amount', 'decimal', 'USD; refunds are negative'),
        col('created_at', 'timestamp', 'Event time, UTC'),
      ],
    },
    reviews: {
      description: 'Product reviews written after delivery. Late deliveries and returns get lower ratings.',
      primaryKey: ['review_id'],
      foreignKeys: [
        { column: 'order_id', references: 'orders.order_id' }, { column: 'product_id', references: 'products.product_id' },
        { column: 'customer_id', references: 'customers.customer_id' },
      ],
      columns: [
        col('review_id', 'text', 'R + 6 digits'), col('order_id', 'text', 'Order the product came in'), col('product_id', 'text', 'Product reviewed'),
        col('customer_id', 'text', 'Reviewer'), col('rating', 'integer', '1–5 stars'),
        col('title', 'text', 'Short headline; often empty', true), col('body', 'text', 'Review text; often empty', true),
        col('created_at', 'timestamp', 'When the review was posted'), col('verified_purchase', 'boolean', 'Always true here'),
      ],
    },
  },
  rawIssues: RAW_ISSUES,
  /** Orders per edition; `full` is everything. Raw exports are built for every edition except preview. */
  editions: { preview: 15, starter: 300, standard: 8000, full: Infinity },
  generate: () => generateMarket(R01_SEED),
  makeRaw,
  cutEdition,
};

export default dataset;
