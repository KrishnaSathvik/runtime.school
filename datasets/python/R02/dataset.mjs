/** Editions keep whole users (with all their ratings and tags) and only the films those users touched. */
const EDITIONS = { preview: { users: 3, maxRatings: 25 }, starter: { users: 120 }, standard: { users: 1500 }, full: { users: Infinity } };

function cutEdition(full, edition) {
  const e = EDITIONS[edition];
  if (e.users === Infinity) return full;
  const byUser = new Map();
  for (const r of full.ratings) (byUser.get(r.user_id) ?? byUser.set(r.user_id, []).get(r.user_id)).push(r);
  const order = full.users.slice().sort((a, b) => hash32(`${edition}|${a.user_id}`) - hash32(`${edition}|${b.user_id}`));
  const keep = new Set();
  let n = 0;
  for (const u of order) {
    const k = byUser.get(u.user_id)?.length ?? 0;
    if (e.maxRatings && (k === 0 || n + k > e.maxRatings)) continue;
    keep.add(u.user_id);
    n += k;
    if (keep.size >= e.users) break;
  }
  const ratings = full.ratings.filter(r => keep.has(r.user_id));
  const tags = full.tags.filter(t => keep.has(t.user_id));
  const used = new Set([...ratings, ...tags].map(r => r.movie_id));
  // Some films nobody in the edition rated, as in the full data (for left-join questions).
  const movies = full.movies.filter(m => used.has(m.movie_id) || (edition !== 'preview' && hash32(`${edition}|m${m.movie_id}`) % 25 === 0));
  const ids = new Set(movies.map(m => m.movie_id));
  return { movies, genres: full.genres, movie_genres: full.movie_genres.filter(g => ids.has(g.movie_id)), users: full.users.filter(u => keep.has(u.user_id)), ratings, tags };
}

export const RAW_ISSUES = {
  'title-with-year': 'Titles with the year appended, e.g. "Glass Harbor (2019)"',
  'title-whitespace': 'Titles with stray spaces',
  'duplicate-ratings': 'The same rating exported twice',
  'rating-out-of-range': 'Ratings outside 0.5–5 (0, 5.5, 10) from an old 10-point import',
  'runtime-text': 'runtime_min written as text ("1h 52m" or "N/A")',
  'timestamp-epoch': 'rated_at written as Unix epoch seconds instead of a date',
  'genre-case': 'Genre names in different case ("science fiction", "SCI-FI")',
};

function makeRaw(t, seed) {
  const rng = createRng(seed);
  const counts = Object.fromEntries(Object.keys(RAW_ISSUES).map(k => [k, 0]));
  const sample = (rows, rate) => new Set(rng.shuffle(rows.map((_, i) => i)).slice(0, rows.length >= 10 ? Math.max(1, Math.round(rows.length * rate)) : 0));
  const movies = t.movies.map(m => ({ ...m }));
  for (const i of sample(movies, 0.05)) { movies[i].title = `${movies[i].title} (${movies[i].release_year})`; counts['title-with-year']++; }
  for (const i of sample(movies, 0.03)) { movies[i].title = rng.pick([` ${movies[i].title}`, `${movies[i].title} `, movies[i].title.replace(' ', '  ')]); counts['title-whitespace']++; }
  for (const i of sample(movies, 0.04)) { const r = movies[i].runtime_min; movies[i].runtime_min = r === null || rng.chance(0.3) ? 'N/A' : `${Math.floor(r / 60)}h ${r % 60}m`; counts['runtime-text']++; }
  const ratings = t.ratings.map(r => ({ ...r }));
  for (const i of sample(ratings, 0.004)) { ratings[i].rating = rng.pick([0, 5.5, 10]); counts['rating-out-of-range']++; }
  for (const i of sample(ratings, 0.02)) { ratings[i].rated_at = String(Math.floor(Date.parse(ratings[i].rated_at.replace(' ', 'T') + 'Z') / 1000)); counts['timestamp-epoch']++; }
  for (const i of [...sample(t.ratings, 0.006)].sort((a, b) => b - a)) { ratings.splice(i + 1, 0, { ...ratings[i] }); counts['duplicate-ratings']++; }
  const genres = t.genres.map(g => ({ ...g }));
  for (const g of genres) if (g.name === 'Science Fiction') { g.name = 'science fiction'; counts['genre-case']++; }
  for (const g of genres) if (g.name === 'Biography') { g.name = 'BIOGRAPHY'; counts['genre-case']++; }
  return { tables: { movies, ratings, genres }, counts };
}

