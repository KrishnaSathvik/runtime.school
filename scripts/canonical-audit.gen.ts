/**
 * Publishes the canonical dataset rebuild audit to docs/canonical-rebuild/ from the sources:
 * dataset inventory and contracts, the Learn and Practice audits, coverage, distribution and performance.
 *   npx vitest run --config vitest.scripts.config.ts scripts/canonical-audit.gen.ts
 * Performance tables read docs/canonical-rebuild/browser-results.json and network-results.json
 * (written by tests/e2e/canonical.mjs and tests/e2e/canonical-network.mjs).
 */
import fs from "node:fs";
import { it } from "vitest";
import manifest from "@/data/datasets/generated/canonical.json";
import { lessons } from "@/content";
import { canonicalLessons } from "@/content/canonical/lessons";
import { canonicalQuestions } from "@/content/question-bank/canonical";
import { DIFFICULTIES, DIFFICULTY_LABEL, EXERCISE_LABEL } from "@/content/question-bank/types";
import { familyLabel, familyOf, topicFamilies, topicLabel } from "@/content/question-bank/topics";

const OUT = "docs/canonical-rebuild";
const NOTE = "<!-- Generated by scripts/canonical-audit.gen.ts. Do not edit by hand. -->";
type Entry = (typeof manifest)[keyof typeof manifest];
type Meta = Entry["metadata"] & { source: Record<string, string | string[]>; coverage: Record<string, string>; edgeCases: string[]; qualityNotes: string[]; reproduction: Record<string, string | number>; kind: string };
const datasets = Object.entries(manifest as Record<string, Entry>).map(([id, e]) => ({ id, e, m: e.metadata as Meta }));
const md = (v: unknown) => String(v ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");
const table = (head: string[], rows: unknown[][]) => [`| ${head.join(" | ")} |`, `| ${head.map(() => "---").join(" | ")} |`, ...rows.map((r) => `| ${r.map(md).join(" | ")} |`)].join("\n");
const mb = (bytes: number) => `${(bytes / 1e6).toFixed(1)} MB`;
const n = (x: number) => x.toLocaleString("en-US");
const nameOf = Object.fromEntries(datasets.map((d) => [d.id, d.m.name]));
const write = (file: string, text: string) => fs.writeFileSync(`${OUT}/${file}`, `${text.trim()}\n`);
type Benchmark = { name: string; gzipBytes: number; databaseBytes: number; factRows: number; coldLoadMs: number; warmReloadMs: number; queries: Record<string, number>; lessonChecks: { count: number; maxMs: number }; practiceChecks: { count: number; medianMs: number; maxMs: number } };
type NetworkRow = { profile: string; dataset: string; firstQueryMs: number };
const readJson = (file: string) => (fs.existsSync(`${OUT}/${file}`) ? JSON.parse(fs.readFileSync(`${OUT}/${file}`, "utf8")) : null);

it("publishes the canonical rebuild audit", () => {
  fs.mkdirSync(OUT, { recursive: true });

  /* ---------------- DATASETS.md ---------------- */
  const totalRows = datasets.reduce((s, d) => s + d.m.totals.rows, 0);
  const summary = table(
    ["Dataset", "Kind", "Rows", "Tables", "Columns", "Coverage", "SQLite size", "Download (gzip)", "Licence"],
    datasets.map(({ m, e }) => [m.name, m.kind, n(m.totals.rows), m.totals.tables, m.totals.columns, `${m.coverage.start} → ${m.coverage.end}`, mb(e.asset.bytes), mb(e.asset.gzipBytes), m.source.license]),
  );
  const details = datasets.map(({ id, e, m }) => {
    const tables = table(["Table", "Rows", "Columns", "Grain"], m.tables.map((t) => [t.name, n(m.rows[t.name as keyof typeof m.rows]), t.columns.length, t.grain]));
    const transformations = (m.source.transformations as string[]).map((t) => `- ${t}`).join("\n");
    return `## ${m.name} (\`${id}\`, version ${m.version})

${m.description}

- **Kind:** ${m.kind}. **Publisher:** ${m.source.publisher}. **Source:** ${m.source.url}
- **Release:** ${m.source.release}
- **Licence:** ${m.source.license} (${m.source.licenseUrl}); commercial reuse: ${m.source.commercialReuse}.
- **Attribution:** ${m.source.attribution}
- **Retrieved:** ${m.source.retrieved}. **Reproduce:** \`${m.reproduction.command}\`${m.reproduction.seed !== undefined ? ` (seed ${m.reproduction.seed})` : ""}
- **Coverage:** ${m.coverage.start} to ${m.coverage.end}, grain: ${m.coverage.grain}
- **Asset:** \`${e.asset.url}\`, ${mb(e.asset.bytes)} SQLite, ${mb(e.asset.gzipBytes)} gzip, SHA-256 \`${e.asset.sha256}\`

${tables}

**Transformations**

${transformations}

**Intentional edge cases**

${m.edgeCases.map((x) => `- ${x}`).join("\n")}

**Quality notes for learners**

${m.qualityNotes.map((x) => `- ${x}`).join("\n")}`;
  });
  write("DATASETS.md", `# Canonical dataset inventory

${NOTE}

Learn and Practice use exactly twelve datasets, one identity each (\`datasetId\` + \`datasetVersion\`), with no edition or size selector. Total: **${n(totalRows)} rows** in ${datasets.reduce((s, d) => s + d.m.totals.tables, 0)} tables. Every dataset is built by \`npm run datasets:canonical\` from committed extracts (real sources) or deterministic generators (synthetic), and is served as a content-hashed, immutably cached gzip SQLite file.

${summary}

Real sources are U.S. government works (public domain), NYC Open Data (free commercial use), CC BY 4.0 (UCI Online Retail II) or Retrosheet (free commercial use with its notice). Synthetic datasets are generated by Runtime with fixed seeds; Healthcare is synthetic only and contains no real patient data.

${details.join("\n\n")}`);

  /* ---------------- CONTRACTS.md ---------------- */
  const contracts = datasets.map(({ m, e }) => {
    const results = e.contract as { name: string; value: unknown; ok: boolean; expectation: string }[];
    const custom = results.filter((r) => !r.name.startsWith("schema "));
    return `## ${m.name}: ${results.filter((r) => r.ok).length}/${results.length} checks pass

${table(["Check", "Value", "Expectation", "Result"], custom.map((r) => [r.name, typeof r.value === "number" ? n(r.value) : r.value, r.expectation, r.ok ? "pass" : "FAIL"]))}

Plus ${results.length - custom.length} schema checks (every declared table has exactly its declared columns, in order).`;
  });
  write("CONTRACTS.md", `# Dataset contracts

${NOTE}

Each dataset declares a contract that the build enforces (the build fails on any violation) and \`tests/canonical/datasets.test.ts\` re-runs against the shipped file. Contracts cover the exact schema, foreign-key integrity, per-table minimum rows (so a dataset cannot silently shrink), a total-row range, date coverage, category diversity, maximum key concentration, and the intentional NULLs, duplicates and edge cases the lessons rely on. The test suite also checks the SHA-256 of every shipped file, the licence fields, the scale targets (75K–250K rows per dataset, 1.3M–1.8M in total, 5–10 tables, 40–80 columns) and that each dataset’s changed-data fixture applies cleanly, keeps relationships valid and rolls back completely.

Fact-table width: every dataset’s main fact table has at least 8 columns except Retail, whose invoice lines carry every field the UCI Online Retail II source provides (7 columns across the line; the source has 8 fields in total, split across \`orders\` and \`order_items\`).

${contracts.join("\n\n")}`);

  /* ---------------- LEARN_AUDIT.md ---------------- */
  const learnRows = lessons.map((l) => {
    const spec = canonicalLessons[l.id];
    return [l.id, l.title, spec.decision, nameOf[l.dataset], spec.reason, l.tasks.map((t) => (t.ordered ? "ordered" : "any order")).join(" / ")];
  });
  const byDecision = (d: string) => lessons.filter((l) => canonicalLessons[l.id].decision === d).length;
  write("LEARN_AUDIT.md", `# Learn audit: all 88 lessons

${NOTE}

Every lesson keeps its id, title (unless it named retired data), module, prerequisites and the ids of its two challenges, so progress and drafts stay attached. Each lesson was re-authored on the dataset locked by the rebuild specification. **KEEP** keeps the teaching content as it was; **MIGRATE** keeps the objective and moves the examples, walkthrough, challenges and concept check to the canonical schema; **REWRITE** changes the task or scenario because the old one depended on retired fixture data or did not transfer. Nothing was retired.

Decisions: KEEP ${byDecision("KEEP")}, MIGRATE ${byDecision("MIGRATE")}, REWRITE ${byDecision("REWRITE")}.

Every challenge answer passes its own check through the shipped worker on the full dataset, empty and truncated variants are rejected, every example and walkthrough step runs, and the changed-data fixture changes every answer except the two DDL lessons (58, 60), whose output is constant by design and which are verified by schema validators instead (\`tests/canonical/learn.test.ts\`).

${table(["ID", "Lesson", "Decision", "Dataset", "Reason", "Challenges"], learnRows)}`);

  /* ---------------- PRACTICE_AUDIT.md ---------------- */
  const practiceRows = canonicalQuestions.map((q) =>
    [q.id, q.title, q.decision, EXERCISE_LABEL[q.exerciseType ?? "write"], DIFFICULTY_LABEL[q.difficulty], topicLabel[q.primaryTopic], nameOf[q.datasetId], q.slug, q.objective, q.wrong.length]);
  const decisions = (d: string) => canonicalQuestions.filter((q) => q.decision === d).length;
  write("PRACTICE_AUDIT.md", `# Practice audit: every question

${NOTE}

Every question runs on one canonical dataset and has its own title-based slug. **MIGRATE** keeps the skill and wording intent on a canonical dataset; **REWRITE** replaces a task that only made sense on the retired fixture; **NEW** is a question added for a weak area.

Decisions: MIGRATE ${decisions("MIGRATE")}, REWRITE ${decisions("REWRITE")}, NEW ${decisions("NEW")}. Formats: ${(["write", "predict", "debug"] as const).map((t) => `${EXERCISE_LABEL[t]} ${canonicalQuestions.filter((q) => (q.exerciseType ?? "write") === t).length}`).join(", ")}.

Every reference solution and authored equivalent passes through the production request path; every listed wrong approach is valid SQL that fails grading; every Debug starter fails; and the changed-data fixture changes every Write/Debug answer (\`tests/canonical/practice.test.ts\`, \`tests/canonical/engine-features.test.ts\`). Ten of the trickiest answers are also recomputed independently in TypeScript from raw rows (\`tests/canonical/anchors.test.ts\`).

${table(["ID", "Title", "Decision", "Format", "Difficulty", "Primary topic", "Dataset", "Slug", "Objective", "Wrong answers"], practiceRows)}`);

  /* ---------------- COVERAGE.md ---------------- */
  const fams = topicFamilies.map((f) => f.id);
  const famRows = fams.map((f) => {
    const inFam = canonicalQuestions.filter((q) => familyOf(q.primaryTopic) === f);
    return [familyLabel[f], ...DIFFICULTIES.map((d) => inFam.filter((q) => q.difficulty === d).length), inFam.length];
  });
  famRows.push(["**Total**", ...DIFFICULTIES.map((d) => canonicalQuestions.filter((q) => q.difficulty === d).length), canonicalQuestions.length]);
  const weak: [string, string[]][] = [
    ["Fill-forward", ["qb-0115", "qb-0116", "qb-0096"]],
    ["Interval merging", ["qb-0100", "qb-0117", "qb-0118"]],
    ["Gaps and islands / consecutive events", ["qb-0113", "qb-0119", "qb-0120", "qb-0121"]],
    ["Correlated subqueries", ["qb-0096", "qb-0122", "qb-0123"]],
    ["Relational division", ["qb-0093", "qb-0124"]],
    ["Hierarchies", ["qb-0097", "qb-0103", "qb-0125", "qb-0126"]],
    ["Histograms and distributions", ["qb-0127", "qb-0128", "qb-0129"]],
    ["Graph-like relationships", ["qb-0130", "qb-0131"]],
    ["Symmetric and asymmetric pairs", ["qb-0114", "qb-0132", "qb-0133"]],
    ["Deduplication", ["qb-0112", "qb-0134", "qb-0137"]],
    ["Interval overlap", ["qb-0135"]],
    ["Predict: NULL, COUNT, LEFT JOIN, ties, frames, fan-out, dates", ["qb-0072", "qb-0073", "qb-0074", "qb-0075", "qb-0076", "qb-0077", "qb-0101", "qb-0102", "qb-0103", "qb-0104", "qb-0105", "qb-0106", "qb-0136", "qb-0138"]],
    ["Debug: NULL, ON vs WHERE, COUNT, ties, boundaries, frames, grain, dedupe", ["qb-0078", "qb-0079", "qb-0080", "qb-0081", "qb-0082", "qb-0083", "qb-0107", "qb-0108", "qb-0109", "qb-0110", "qb-0111", "qb-0112", "qb-0137", "qb-0139"]],
  ];
  write("COVERAGE.md", `# Coverage

${NOTE}

## Practice: topic family × difficulty (primary topic)

${table(["Topic family", ...DIFFICULTIES.map((d) => DIFFICULTY_LABEL[d]), "Total"], famRows)}

## Practice: patterns that were thin before the rebuild

${table(["Pattern", "Questions"], weak.map(([p, ids]) => [p, ids.join(", ")]))}

## Practice: dataset × format

${table(["Dataset", ...(["write", "predict", "debug"] as const).map((t) => EXERCISE_LABEL[t]), "Total"], datasets.map(({ id, m }) => { const qs = canonicalQuestions.filter((q) => q.datasetId === id); return [m.name, ...(["write", "predict", "debug"] as const).map((t) => qs.filter((q) => (q.exerciseType ?? "write") === t).length), qs.length]; }))}`);

  /* ---------------- DISTRIBUTION.md ---------------- */
  write("DISTRIBUTION.md", `# Dataset distribution

${NOTE}

Learn uses datasets for continuity: one dataset carries a run of related lessons (Retail carries the foundations and the whole warehouse sequence, 69–87 except 75). Practice uses datasets for transfer: the same skill is practised on a different domain from the one it was taught on.

${table(["Dataset", "Lessons", "Lesson ids", "Practice questions", "Learn challenges + Practice"], datasets.map(({ id, m }) => { const ls = lessons.filter((l) => l.dataset === id); const qs = canonicalQuestions.filter((q) => q.datasetId === id); return [m.name, ls.length, ls.map((l) => l.id).join(", "), qs.length, ls.length * 2 + qs.length]; }))}

## Transfer: Practice questions on a different dataset from their prerequisite lessons

${(() => { const transfer = canonicalQuestions.filter((q) => q.prerequisites.length && q.prerequisites.every((p) => lessons[p].dataset !== q.datasetId)).length; return `${transfer} of ${canonicalQuestions.filter((q) => q.prerequisites.length).length} questions with prerequisites are set on a different dataset from every lesson they build on.`; })()}`);

  /* ---------------- PERFORMANCE.md ---------------- */
  const browser = readJson("browser-results.json");
  const network = readJson("network-results.json");
  const perf = browser ? table(["Dataset", "Download", "SQLite", "Fact rows", "Cold load (loopback)", "Warm reload", "Preview", "Filter", "GROUP BY", "JOIN", "Window", "Learn checks (max)", "Practice checks (median / max)"],
    (browser.benchmarks as Benchmark[]).map((b) => [b.name, mb(b.gzipBytes), mb(b.databaseBytes), n(b.factRows), `${b.coldLoadMs} ms`, `${b.warmReloadMs} ms`, `${b.queries["preview (12 rows)"]} ms`, `${b.queries.filter} ms`, `${b.queries["group by"]} ms`, `${b.queries.join} ms`, `${b.queries["window (full partition sort)"]} ms`, `${b.lessonChecks.count} (${b.lessonChecks.maxMs} ms)`, `${b.practiceChecks.count} (${b.practiceChecks.medianMs} / ${b.practiceChecks.maxMs} ms)`])) : "_Run tests/e2e/canonical.mjs to measure._";
  const net = network ? (() => { const profiles = [...new Set((network.rows as { profile: string }[]).map((r) => r.profile))]; return table(["Dataset", "Download", ...profiles], datasets.map(({ id, m, e }) => [m.name, mb(e.asset.gzipBytes), ...profiles.map((p) => `${(network.rows as NetworkRow[]).find((r) => r.profile === p && r.dataset === id)?.firstQueryMs ?? "–"} ms`)])); })() : "_Run tests/e2e/canonical-network.mjs to measure._";
  write("PERFORMANCE.md", `# Browser performance

${NOTE}

Measured in ${browser?.browser ?? "headless Chromium"} against a production build, through the shipped worker (\`public/vendor/engine.js\`) on the full datasets. Each dataset ran in a fresh browser context (empty HTTP cache). “Cold load” is download + gzip decompression + SHA-256 verification + opening the database + the first query; over loopback it measures processing only. “Warm reload” opens the same dataset in a new worker with the file in the HTTP cache. Learn and Practice checks are the exact Check requests (visible data, changed-data fixture, validators and plan checks), every one of which passed.

${perf}

## First load over a throttled connection

${network?.method ?? ""}. The time is dominated by download size; once loaded the file is cached permanently (content-hashed URL, \`Cache-Control: public, max-age=31536000, immutable\`), and lesson and question pages start the download while the learner reads.

${net}

## What was optimised before considering smaller data

- Binary SQLite files (VACUUMed, ANALYZEd, gzip level 9) instead of SQL text seeds, decompressed with the browser’s DecompressionStream and verified by SHA-256.
- One read-only connection per dataset shared by Run and Check; the changed-data check runs inside a savepoint and rolls back instead of rebuilding the database.
- Covering and composite indexes for the access paths lessons and questions use (for example \`products(category_id, is_merchandise, list_price)\`, \`events(account_id, occurred_at)\`), and query rewrites where a correlated EXISTS over a window CTE or an unscoped FULL OUTER JOIN was slow.
- Content-hashed asset URLs with immutable caching, and preloading on lesson and question pages.
- Previews of 12 rows (20 for small samples) ship with the page; queries always run on the full data.

No dataset was reduced in scale for performance.`);
});

