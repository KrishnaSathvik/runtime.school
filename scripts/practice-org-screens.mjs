import { chromium } from "playwright";
import fs from "fs";
const BASE = process.env.BASE ?? "http://127.0.0.1:3232";
const OUT = "docs/practice/screens";
fs.mkdirSync(OUT, { recursive: true });
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
await page.goto(`${BASE}/practice`, { waitUntil: "networkidle" });
await page.screenshot({ path: `${OUT}/01-practice-hub.png`, fullPage: true });
await page.goto(`${BASE}/practice/questions`, { waitUntil: "networkidle" });
await page.getByRole("status").filter({ hasText: /questions/ }).waitFor();
await page.screenshot({ path: `${OUT}/02-browser-independent-default.png`, fullPage: true });
await page.getByLabel("Source", { exact: true }).selectOption("lessons");
await page.waitForURL(/source=lessons/);
await page.screenshot({ path: `${OUT}/03-browser-from-learn.png`, fullPage: true });
await page.goto(`${BASE}/practice/tracks/sql-from-zero`, { waitUntil: "networkidle" });
await page.getByRole("heading", { name: "SQL from Zero" }).waitFor();
await page.screenshot({ path: `${OUT}/04-track-sql-from-zero.png`, fullPage: true });
await page.goto(`${BASE}/practice/tracks/master-joins`, { waitUntil: "networkidle" });
await page.screenshot({ path: `${OUT}/05-track-master-joins.png`, fullPage: true });
await browser.close();
console.log("screenshots written to", OUT);
