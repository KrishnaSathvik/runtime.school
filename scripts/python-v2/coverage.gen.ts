/**
 * Dataset-to-content coverage report (plan §3).
 *   npm run py:coverage   → docs/python/coverage.md
 * A dataset counts as built when src/content/python-v2/datasets/<id>.json (its manifest) exists.
 */
import { it } from "vitest";
import fs from "node:fs";
import { coverageReport, pyRegistry, validateRegistry } from "@/content/python-v2/registry";
import { authoredLessons, authoredProjects, authoredQuestions } from "@/content/python-v2/content";
import { toolDatasets } from "@/content/python-v2/tools/friendly";
import { STARTERS } from "@/content/python-v2/tools/starters";
import { LAB_ACTIVITIES, LAB_ENVIRONMENTS, activityEnvs } from "@/content/python-v2/tools/lab";
import { DUCKDB_ACTIVITIES } from "@/content/python-v2/tools/lab-duckdb";
import { EXPERIMENTS, PERF_CATEGORIES } from "@/content/python-v2/tools/performance";
import { COMPARE_CATEGORIES, COMPARISONS } from "@/content/python-v2/tools/compare";

/**
 * What actually loads each dataset today, as opposed to what the registry plans: authored content that mounts the
 * dataset's files, projects that name it, and every Python tool entry that runs on it.
 */
function actualUse(id: string) {
  const mounts = (x: unknown) => JSON.stringify(x).includes(`"url":"/datasets/python/${id}/`);
  const lessons = authoredLessons.filter(mounts).map((l) => l.id);
  const questions = authoredQuestions.filter(mounts).map((q) => q.id);
  const projectsMounting = authoredProjects.filter(mounts).map((p) => p.id);
  const projectsNaming = authoredProjects.filter((p) => p.dataset.startsWith(`${id}@`) && !projectsMounting.includes(p.id)).map((p) => p.id);
  const envs = LAB_ENVIRONMENTS.filter((e) => e.dataset === id);
  const labActivities = LAB_ACTIVITIES.filter((a) => a.data?.dataset === id || activityEnvs(a).some((e) => envs.some((x) => x.id === e))).length;
  return {
    lessons, questions, projectsMounting, projectsNaming,
    starters: STARTERS.filter((s) => s.dataset === id).map((s) => s.id),
    lab: envs.length ? `${envs.map((e) => e.name).join(", ")} environment, ${labActivities} activities` : LAB_ACTIVITIES.some((a) => a.data?.dataset === id) ? "data for an activity" : "",
    experiments: EXPERIMENTS.filter((e) => e.dataset?.id === id).map((e) => e.id),
    comparisons: COMPARISONS.filter((c) => c.data?.dataset === id).map((c) => c.id),
  };
}

const MANIFESTS = "src/content/python-v2/datasets";
const OUT = "docs/python/coverage.md";

it("writes the coverage report", () => {
  const built = new Set(fs.existsSync(MANIFESTS) ? fs.readdirSync(MANIFESTS).filter((f) => f.endsWith(".json")).map((f) => f.slice(0, -5)) : []);
  const r = coverageReport(pyRegistry, built);
  const problems = validateRegistry(pyRegistry, built);
  const table = (c: Record<string, number>) => Object.entries(c).sort().map(([k, v]) => `| ${k} | ${v} |`).join("\n");
  const blockedByReason: Record<string, Record<string, number>> = {};
  for (const b of r.blocked) (blockedByReason[b.dataset] ??= {})[b.reason] = (blockedByReason[b.dataset]?.[b.reason] ?? 0) + 1;

  const md = `# Python coverage report

Generated by \`npm run py:coverage\` from \`src/content/python-v2/registry.json\`. Don't edit by hand.

Registry validation: ${problems.length ? `**${problems.length} problems**\n\n${problems.map((p) => `- ${p}`).join("\n")}` : "no problems."}

## Datasets

| Dataset | Licence | Built | Lessons | Questions | Projects | Modules |
|---|---|---|---:|---:|---|---|
${r.datasets.map((d) => `| ${d.id} ${d.title} | ${d.licence} | ${d.built ? "yes" : "no"} | ${d.lessons} | ${d.questions} | ${d.projects.join(", ")} | ${d.modules.join(", ")} |`).join("\n")}

**Unused datasets:** ${r.unused.length ? r.unused.join(", ") : "none"}

## What actually uses each dataset

The table above is the plan (registry). This one is what runs today: authored content whose files mount the dataset,
projects that only name it (they ship their own sample files), and the Python tools.

| Dataset | Learner name | Lessons mounting | Questions mounting | Projects mounting | Projects naming it | Playground starters | Database Lab | Performance Lab | Comparator |
|---|---|---:|---:|---|---|---|---|---|---|
${toolDatasets.map((d) => { const u = actualUse(d.id); return `| ${d.id} | ${d.name} | ${u.lessons.length} | ${u.questions.length} | ${u.projectsMounting.join(", ") || "—"} | ${u.projectsNaming.join(", ") || "—"} | ${u.starters.length} | ${u.lab || "—"} | ${u.experiments.length} | ${u.comparisons.length} |`; }).join("\n")}

Lessons and practice questions use inline data today; none mounts a dataset edition yet.

## Python tools

| Tool | What's there |
|---|---|
| Datasets | ${toolDatasets.length} datasets |
| Python Playground | ${STARTERS.length} ready-made programs; any dataset can be attached |
| Python Database Lab | ${LAB_ENVIRONMENTS.length} dataset databases plus an empty one; ${LAB_ACTIVITIES.length} activities, ${LAB_ACTIVITIES.filter((a) => a.id.startsWith("duckdb")).length} of them DuckDB (${DUCKDB_ACTIVITIES.length} in lab-duckdb.ts) |
| Performance Lab | ${EXPERIMENTS.length} experiments: ${PERF_CATEGORIES.map((c) => `${c} ${EXPERIMENTS.filter((e) => e.category === c).length}`).join(", ")} |
| Compare Approaches | ${COMPARISONS.length} comparisons: ${COMPARE_CATEGORIES.map((c) => `${c} ${COMPARISONS.filter((x) => x.category === c).length}`).join(", ")} |

## Content that can't be published yet because of its data

| Dataset | Reason | Items |
|---|---|---:|
${Object.entries(blockedByReason).sort().flatMap(([d, reasons]) => Object.entries(reasons).map(([why, n]) => `| ${d} | ${why} | ${n} |`)).join("\n")}

Total: ${r.blocked.length} item references.

## Status

| Kind:status | Count |
|---|---:|
${table(r.byStatus)}

## Mode

| Kind:mode | Count |
|---|---:|
${table(r.byMode)}

## Question formats

| Format | Count |
|---|---:|
${table(r.byFormat)}

## By stage

| Stage | Count |
|---|---:|
${table(r.byStage)}
`;
  fs.writeFileSync(OUT, md);
});
