/**
 * Register every authored PySpark file with the app: items, lessons, dataset snapshots and project definitions.
 *
 *   node scripts/pyspark/build-index.mjs
 *
 * Writes src/content/pyspark/generated.ts (static imports, so Next bundles them). Run it after adding or removing a
 * file in src/content/pyspark/{items,lessons,datasets,projects}; content.ts reads only this index.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const dir = path.join(root, 'src/content/pyspark');
const list = (sub, test) => fs.readdirSync(path.join(dir, sub)).filter(test).sort();

const items = list('items', (f) => f.endsWith('.json') && !f.endsWith('.expected.json')).map((f) => f.replace(/\.json$/, ''));
const lessons = list('lessons', (f) => f.endsWith('.json') && !f.endsWith('.recorded.json')).map((f) => f.replace(/\.json$/, ''));
const datasets = list('datasets', (f) => f.endsWith('.json')).map((f) => f.replace(/\.json$/, ''));
const projects = list('projects', (f) => f.endsWith('.json')).map((f) => f.replace(/\.json$/, ''));

for (const id of items) if (!fs.existsSync(path.join(dir, 'items', `${id}.expected.json`))) throw new Error(`${id}: no .expected.json (run build-expected)`);
for (const id of lessons) if (!fs.existsSync(path.join(dir, 'lessons', `${id}.recorded.json`))) throw new Error(`${id}: no .recorded.json (run build-lesson)`);

const v = (id) => id.replace(/[^A-Za-z0-9]/g, '_');
const lines = [
  '// Generated by scripts/pyspark/build-index.mjs. Do not edit by hand.',
  ...items.flatMap((id) => [`import i_${v(id)} from "./items/${id}.json";`, `import e_${v(id)} from "./items/${id}.expected.json";`]),
  ...lessons.flatMap((id) => [`import l_${v(id)} from "./lessons/${id}.json";`, `import r_${v(id)} from "./lessons/${id}.recorded.json";`]),
  ...datasets.map((id) => `import d_${v(id)} from "./datasets/${id}.json";`),
  ...projects.map((id) => `import p_${v(id)} from "./projects/${id}.json";`),
  '',
  `export const ITEM_FILES: [unknown, unknown][] = [${items.map((id) => `[i_${v(id)}, e_${v(id)}]`).join(', ')}];`,
  `export const LESSON_FILES: Record<string, [unknown, unknown]> = { ${lessons.map((id) => `"${id}": [l_${v(id)}, r_${v(id)}]`).join(', ')} };`,
  `export const DATASET_FILES: Record<string, unknown> = { ${datasets.map((id) => `"${id}": d_${v(id)}`).join(', ')} };`,
  `export const PROJECT_FILES: Record<string, unknown> = { ${projects.map((id) => `"${id}": p_${v(id)}`).join(', ')} };`,
  '',
];
fs.writeFileSync(path.join(dir, 'generated.ts'), lines.join('\n'));
console.log(`Indexed ${items.length} items, ${lessons.length} lessons, ${datasets.length} datasets, ${projects.length} projects`);
