/**
 * Generates the question-bank inventory from canonical sources:
 *   - src/content/question-bank/examples.json (sample output shown in the UI)
 *   - docs/question-bank/question-manifest.json
 *   - generated docs/question-bank/*.md
 * Run: npm run qb:report. Tests fail if examples.json or the manifest are stale.
 */
