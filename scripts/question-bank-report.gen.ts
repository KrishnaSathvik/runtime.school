const DOCS = "docs/question-bank";
const GEN_NOTE = "<!-- Generated by `npm run qb:report` from canonical sources. Do not edit by hand. -->";
const D = (d: Difficulty) => DIFFICULTY_LABEL[d];
const md = (s: unknown) => String(s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");
const count = <T>(xs: T[], f: (x: T) => boolean) => xs.filter(f).length;
const pct = (n: number, d: number) => (d ? `${Math.round((100 * n) / d)}%` : "–");

function table(head: string[], rows: Array<Array<string | number>>): string {
  return [
    `| ${head.join(" | ")} |`,
    `| ${head.map(() => "---").join(" | ")} |`,
    ...rows.map((r) => `| ${r.map(md).join(" | ")} |`),
  ].join("\n");
}

function matrix(rows: QuestionRecord[], title: string): string {
  const fams = topicFamilies.map((f) => f.id);
  const body = fams.map((f) => {
    const inFam = rows.filter((q) => familyOf(q.primaryTopic) === f);
    return [familyLabel[f], ...DIFFICULTIES.map((d) => count(inFam, (q) => q.difficulty === d)), inFam.length];
  });
  body.push(["**Total**", ...DIFFICULTIES.map((d) => count(rows, (q) => q.difficulty === d)), rows.length]);
  return `### ${title}\n\n${table(["Topic family (primary topic)", ...DIFFICULTIES.map(D), "Total"], body)}`;
}

it("generate question-bank inventory", async () => {
  fs.mkdirSync(DOCS, { recursive: true });
  const all = allQuestions();
  const existing = all.filter((q) => q.sourceType !== "bank");
  const bank = all.filter((q) => q.sourceType === "bank");
  const examples = await computeExamples();
  fs.writeFileSync("src/content/question-bank/input-previews.json",JSON.stringify(await computeInputPreviews(),null,2)+"\n");
  const outputs = await existingOutputs();
  const tables = await tableInfo();
  const today = "2026-10-09";

  fs.writeFileSync("src/content/question-bank/examples.json", JSON.stringify(examples, null, 2) + "\n");

  /* ---------- machine-readable manifest ---------- */
  const manifest = {
    generatedFrom: "src/content (content-pack.json, question-bank/*)",
    counts: {
      total: all.length,
      byExerciseType: Object.fromEntries(["write", "predict", "debug"].map(type => [type, count(all, q => (q.exerciseType ?? "write") === type)])),
      lessons: lessons.length,
      tracks: tracks.length,
      projects: projects.length,
      existing: existing.length,
      existingLesson: count(existing, (q) => q.sourceType === "lesson"),
      existingProject: count(existing, (q) => q.sourceType === "project"),
      bank: bank.length,
      practiceEligible: count(all, (q) => q.practiceEligible),
      byDifficulty: Object.fromEntries(DIFFICULTIES.map((d) => [d, count(all, (q) => q.difficulty === d)])),
      datasets: Object.keys(practiceDatasets).length,
      newDatasets: Object.keys(practiceDatasets).filter(id => ["market", "org", "reasoning", "capacity"].includes(id)),
    },
    questions: all.map((q) => {
      const isBank = q.sourceType === "bank";
      const b = isBank ? bankQuestions.find((x) => x.id === q.id)! : null;
      const sql = isBank ? b!.solution : lessons[q.sourceLessonId!].tasks[q.sourceVariant!].answer;
      const validators = isBank ? b!.validate?.length ?? 0 : lessons[q.sourceLessonId!].tasks[q.sourceVariant!].validate?.length ?? 0;
      const r = rubricFor(sql, validators);
      return {
        ...q,
        ...(isBank ? { caseStudy: b!.caseStudy, setupSql: b!.setupSql, extraMutation: b!.extraMutation, equivalentSolutions: b!.equivalent ?? [] } : {}),
        rubric: { score: r.score, difficulty: r.difficulty },
        tables: r.features.tables,
        expectedColumns: isBank ? examples[q.id].columns : outputs[q.id]?.columns ?? [],
        grading: {
          resultCompare: true,
          ordered: q.ordered,
          changedData: q.exerciseType !== "predict",
          prediction: q.exerciseType === "predict",
          requiredConstructs: isBank ? b!.required ?? null : lessons[q.sourceLessonId!].tasks[q.sourceVariant!].required,
          validators,
          repeatCheck: isBank ? b!.repeatCheck ?? false : false,
          stateQueries: isBank ? b!.stateQueries ?? [] : [],
          planValidation: isBank ? b!.planValidation : lessons[q.sourceLessonId!].tasks[q.sourceVariant!].planValidation,
        },
      };
    }),
  };
  fs.writeFileSync(`${DOCS}/question-manifest.json`, JSON.stringify(manifest, null, 2) + "\n");

  /* ---------- EXISTING_QUESTIONS.md ---------- */
  const exRows = existing.map((q) => {
    const l = lessons[q.sourceLessonId!];
    const t = l.tasks[q.sourceVariant!];
    const r = rubricFor(t.answer, t.validate?.length ?? 0);
    const grading = [
      "result compare",
      "changed data",
      t.ordered ? "ordered" : "any order",
      t.required?.length ? `requires ${t.required.join(", ")}` : "",
      t.validate?.length ? `${t.validate.length} object checks` : "",
    ]
      .filter(Boolean)
      .join("; ");
    return [
      q.id,
      `${q.sourceLessonId} · ${l.title}`,
      `${l.group + 1}`,
      q.prompt,
      q.primaryTopic,
      q.topicTags.join(", "),
      `${D(q.difficulty)}${q.difficulty !== r.difficulty ? ` (rubric ${D(r.difficulty)})` : ""}`,
      q.datasetId,
      r.features.tables.join(", "),
      (outputs[q.id]?.columns ?? []).join(", "),
      grading,
      q.pattern,
      q.practiceEligible ? "yes" : "lesson only",
      q.projectIds?.map((p) => projects[p].title).join(", ") ?? "",
    ];
  });
  fs.writeFileSync(
    `${DOCS}/EXISTING_QUESTIONS.md`,
    `# Existing questions (${existing.length})\n\n${GEN_NOTE}\n\nEvery challenge from the 88 lessons, classified from its reference SQL. Ids are \`lc-<lesson>-<variant>\` and never change; the lesson and its mastery rule (two independent solves + concept check) are untouched. Reference solutions, hints and full features are in \`question-manifest.json\` and \`src/content/content-pack.json\`.\n\nColumns: **Difficulty** is the reviewed value (the rubric's raw call is shown when a reviewer overrode it — see DIFFICULTY_AUDIT.md). **Pattern** groups challenges that need the same reasoning. **Practice** = whether the prompt stands on its own outside its lesson.\n\n${table(
      ["ID", "Lesson", "Module", "Prompt", "Primary topic", "Secondary tags", "Difficulty", "Dataset", "Tables", "Output columns", "Grading", "Pattern", "Practice", "Projects"],
      exRows,
    )}\n`,
  );

  /* ---------- duplicates ---------- */
  const patterns = new Map<string, QuestionRecord[]>();
  for (const q of existing) patterns.set(q.pattern, [...(patterns.get(q.pattern) ?? []), q]);
  const dupGroups = [...patterns.values()].filter((g) => g.length > 1);
  const sameLessonDup = dupGroups.filter((g) => new Set(g.map((q) => q.sourceLessonId)).size === 1);
  const crossLessonDup = dupGroups.filter((g) => new Set(g.map((q) => q.sourceLessonId)).size > 1);

  /* ---------- QUESTION_COVERAGE.md (existing) ---------- */
  const topicRows = topicFamilies.flatMap((f) =>
    f.topics.map((t) => {
      const prim = existing.filter((q) => q.primaryTopic === t.id);
      const tagged = existing.filter((q) => q.primaryTopic === t.id || q.topicTags.includes(t.id));
      return [f.label, t.id, t.label, prim.length, tagged.length, DIFFICULTIES.map((d) => count(prim, (q) => q.difficulty === d)).join(" / ")];
    }),
  );
  const datasetRows = Object.keys(practiceDatasets).map((d) => [
    d,
    practiceDatasets[d].name,
    count(existing, (q) => q.datasetId === d),
    count(bank, (q) => q.datasetId === d),
  ]);
  const weak = topicFamilies.flatMap((f) => f.topics).filter((t) => count(existing, (q) => q.primaryTopic === t.id) <= 1);
  fs.writeFileSync(
    `${DOCS}/QUESTION_COVERAGE.md`,
    `# Coverage of the existing ${existing.length} challenges\n\n${GEN_NOTE}\n\n## By difficulty\n\n${table(
      ["Difficulty", "Challenges", "Share"],
      DIFFICULTIES.map((d) => [D(d), count(existing, (q) => q.difficulty === d), pct(count(existing, (q) => q.difficulty === d), existing.length)]),
    )}\n\n## By module (curriculum position) versus difficulty\n\nModules are *not* difficulty levels — this table shows how they differ.\n\n${table(
      ["Module", ...DIFFICULTIES.map(D)],
      groups.map((g, i) => [`${i + 1}. ${g}`, ...DIFFICULTIES.map((d) => count(existing, (q) => q.moduleId === i && q.difficulty === d))]),
    )}\n\n## By topic\n\n“Primary” = the challenge's main skill; “Tagged” also counts secondary use.\n\n${table(
      ["Family", "Topic id", "Topic", "Primary", "Tagged", "Primary W / E / M / H"],
      topicRows,
    )}\n\n## By dataset\n\n${table(["Dataset", "Name", "Existing challenges", "New bank questions"], datasetRows)}\n\n## Weak topics (≤ 1 primary challenge)\n\n${weak
      .map((t) => `- \`${t.id}\` ${t.label}: ${count(existing, (q) => q.primaryTopic === t.id)} primary, ${count(existing, (q) => q.topicTags.includes(t.id))} secondary`)
      .join("\n")}\n\n## Duplicate patterns\n\n- ${sameLessonDup.length} lessons have two challenges that need the **same reasoning** (structure identical or ≥ 80% similar) — the second challenge rehearses rather than extends.\n- ${crossLessonDup.length} cross-lesson groups have identical structure.\n\n${table(
      ["Pattern", "Challenges", "Lesson(s)"],
      dupGroups.map((g) => [g[0].pattern, g.map((q) => q.id).join(", "), [...new Set(g.map((q) => lessons[q.sourceLessonId!].title))].join("; ")]),
    )}\n\n## Practice eligibility\n\n${count(existing, (q) => q.practiceEligible)} of ${existing.length} challenges make sense outside their lesson and are listed in Practice. The other ${count(existing, (q) => !q.practiceEligible)} depend on earlier lesson context (reviewed list in \`existing.ts\`). They are still reached through their lesson — and, where relevant, their project — at the link shown.\n\n${table(
      ["Challenge", "Lesson", "Why lesson-only", "Reached at"],
      Object.entries(LESSON_ONLY).map(([k, why]) => {
        const [l, v] = k.split("/").map(Number);
        return [`lc-${l}-${v}`, lessons[l].title, why, `/lesson/${l}?challenge=${v + 1}`];
      }),
    )}\n`,
  );

  /* ---------- QUESTION_INVENTORY.md ---------- */
  const bySource = (s: string) => count(all, (q) => q.sourceType === s);
  fs.writeFileSync(
    `${DOCS}/QUESTION_INVENTORY.md`,
    `# Question inventory\n\n${GEN_NOTE}\n\n_Generated ${today}._\n\n## Summary\n\n${table(
      ["Measure", "Count"],
      [
        ["Total unique questions", all.length],
        ["Existing lesson challenges (not in a project)", bySource("lesson")],
        ["Existing challenges that are also project milestones", bySource("project")],
        ["New independent question-bank problems", bySource("bank")],
        ["Listed in the Practice browser (stand-alone)", count(all, (q) => q.practiceEligible)],
        ["Datasets (all)", Object.keys(practiceDatasets).length],
        ["Additional datasets", Object.keys(practiceDatasets).length - 7],
        ["Write SQL exercises", count(all,q=>(q.exerciseType??"write")==="write")],
        ["Predict Output exercises", count(all,q=>q.exerciseType==="predict")],
        ["Debug Query exercises", count(all,q=>q.exerciseType==="debug")],
        ["Project milestone mappings", projects.reduce((n, p) => n + p.milestoneIds.length, 0)],
        ["Untested or incomplete questions", 0],
        ["Practice tracks", tracks.length],
        ["Distinct questions used in tracks", new Set(tracks.flatMap((t) => t.questionIds)).size],
      ],
    )}\n\n“Untested” is 0 because every question's reference answer is executed by the test suite on visible and changed data (\`tests/parity.test.ts\` for the 176, \`tests/question-bank.test.ts\` for the bank).\n\n## By difficulty\n\n${table(
      ["Difficulty", "Existing", "New", "Total"],
      DIFFICULTIES.map((d) => [D(d), count(existing, (q) => q.difficulty === d), count(bank, (q) => q.difficulty === d), count(all, (q) => q.difficulty === d)]),
    )}\n\n## By topic family (primary)\n\n${table(
      ["Family", "Existing", "New", "Total"],
      topicFamilies.map((f) => [f.label, count(existing, (q) => familyOf(q.primaryTopic) === f.id), count(bank, (q) => familyOf(q.primaryTopic) === f.id), count(all, (q) => familyOf(q.primaryTopic) === f.id)]),
    )}\n\n## By dataset\n\n${table(
      ["Dataset", "Existing", "New", "Total"],
      Object.keys(practiceDatasets).map((d) => [`${d} (${practiceDatasets[d].name})`, count(existing, (q) => q.datasetId === d), count(bank, (q) => q.datasetId === d), count(all, (q) => q.datasetId === d)]),
    )}\n\n## By source type\n\n${table(["Source", "Count"], [["lesson", bySource("lesson")], ["project", bySource("project")], ["bank", bySource("bank")]])}\n\nMachine-readable: \`question-manifest.json\`.\n`,
  );

  /* ---------- DIFFICULTY_MATRIX.md ---------- */
  fs.writeFileSync(
    `${DOCS}/DIFFICULTY_MATRIX.md`,
    `# Topic × difficulty matrix\n\n${GEN_NOTE}\n\nCounts by primary topic family. Each question has exactly one primary topic.\n\n${matrix(all, `All questions (${all.length})`)}\n\n${matrix(existing, `Existing challenges (${existing.length})`)}\n\n${matrix(bank, `New question-bank problems (${bank.length})`)}\n`,
  );

  /* ---------- TOPIC_COVERAGE.md ---------- */
  fs.writeFileSync(
    `${DOCS}/TOPIC_COVERAGE.md`,
    `# Topic coverage\n\n${GEN_NOTE}\n\n${table(
      ["Topic id", "Topic", "Existing (primary)", "New (primary)", "All (primary)", "All (tagged anywhere)", "Difficulties present"],
      topicFamilies.flatMap((f) =>
        f.topics.map((t) => {
          const prim = all.filter((q) => q.primaryTopic === t.id);
          return [
            t.id,
            `${f.label} › ${t.label}`,
            count(existing, (q) => q.primaryTopic === t.id),
            count(bank, (q) => q.primaryTopic === t.id),
            prim.length,
            count(all, (q) => q.primaryTopic === t.id || q.topicTags.includes(t.id)),
            [...new Set(prim.map((q) => D(q.difficulty)))].join(", "),
          ];
        }),
      ),
    )}\n`,
  );

  /* ---------- DATASET_INVENTORY.md ---------- */
  const tableRole = (t: string) => Object.entries(practiceDatasets).filter(([, d]) => d.tables.includes(t)).map(([k]) => k);
  const dsSections = Object.entries(practiceDatasets).map(([id, d]) => {
    const uses = all.filter((q) => q.datasetId === id);
    const lessonIds = [...new Set(uses.filter((q) => q.sourceLessonId !== undefined).map((q) => q.sourceLessonId!))];
    const pr = projects.filter((p) => p.dataset === id).map((p) => p.title);
    return `## ${d.name} (\`${id}\`)${["market", "org"].includes(id) ? " — new" : ""}\n\n${d.description}\n\n- Role framing: ${d.role}\n- Questions: ${uses.length} (${DIFFICULTIES.map((x) => `${D(x)} ${count(uses, (q) => q.difficulty === x)}`).join(", ")})\n- Topics: ${[...new Set(uses.map((q) => familyLabel[familyOf(q.primaryTopic)]))].join(", ") || "—"}\n- Lessons: ${lessonIds.length ? lessonIds.map((l) => l).join(", ") : "none"}${pr.length ? `\n- Projects: ${pr.join(", ")}` : ""}\n\n${d.tables
      .map((t) => {
        const info = tables[t];
        if (!info) return `- \`${t}\`: (created by the lab exercises)`;
        const cols = info.columns.map((c) => `${c.name} ${c.type}${c.pk ? " PK" : ""}${c.notnull ? " NOT NULL" : ""}`).join(", ");
        const fk = info.foreignKeys.length ? ` · FK ${info.foreignKeys.map((f) => `${f.column} → ${f.references}`).join(", ")}` : "";
        const shared = tableRole(t).length > 1 ? ` · also in ${tableRole(t).filter((x) => x !== id).join(", ")}` : "";
        return `- \`${t}\` (${info.rows} rows): ${cols}${fk}${shared}`;
      })
      .join("\n")}`;
  });
  const handNotes = fs.existsSync(`${DOCS}/_dataset-notes.md`) ? fs.readFileSync(`${DOCS}/_dataset-notes.md`, "utf8") : "";
  fs.writeFileSync(
    `${DOCS}/DATASET_INVENTORY.md`,
    `# Dataset inventory\n\n${GEN_NOTE}\n\nAll datasets live in one SQLite database per run (curriculum seed + question-bank seed). Lessons load only the curriculum seed, so their results are unchanged.\n\n${dsSections.join("\n\n")}\n\n${handNotes}`,
  );

  /* ---------- DIFFICULTY_AUDIT.md ---------- */
  const order = DIFFICULTIES as readonly string[];
  const bankCal = bankQuestions.map((b) => {
    const r = rubricFor(b.solution, b.validate?.length ?? 0);
    return { b, r, gap: order.indexOf(b.difficulty) - order.indexOf(r.difficulty) };
  });
  const rubricText = fs.existsSync(`${DOCS}/_rubric.md`) ? fs.readFileSync(`${DOCS}/_rubric.md`, "utf8") : "";
  fs.writeFileSync(
    `${DOCS}/DIFFICULTY_AUDIT.md`,
    `# Difficulty audit\n\n${GEN_NOTE}\n\n${rubricText}\n\n## Existing challenges: rubric vs reviewed\n\n${table(
      ["Difficulty", "Rubric", "After review"],
      DIFFICULTIES.map((d) => [
        D(d),
        count(existing, (q) => rubricFor(lessons[q.sourceLessonId!].tasks[q.sourceVariant!].answer, lessons[q.sourceLessonId!].tasks[q.sourceVariant!].validate?.length ?? 0).difficulty === d),
        count(existing, (q) => q.difficulty === d),
      ]),
    )}\n\n### Reviewer overrides (${Object.keys(DIFFICULTY_OVERRIDES).length})\n\n${table(
      ["Challenge", "Lesson", "Final", "Why"],
      Object.entries(DIFFICULTY_OVERRIDES).map(([k, v]) => {
        const [l] = k.split("/").map(Number);
        return [`lc-${k.replace("/", "-")}`, lessons[l].title, D(v.difficulty), v.why];
      }),
    )}\n\n### Lesson label vs question difficulty\n\nThe original lessons carry Beginner/Intermediate/Advanced labels. Question difficulty is independent:\n\n${table(
      ["Lesson label", ...DIFFICULTIES.map(D)],
      ["Beginner", "Intermediate", "Advanced"].map((lab) => [lab, ...DIFFICULTIES.map((d) => count(existing, (q) => lessons[q.sourceLessonId!].difficulty === lab && q.difficulty === d))]),
    )}\n\n## New questions: assigned vs rubric (calibration)\n\n**${count(bankCal, (x) => x.gap === 0)} of ${bankCal.length} agree with the rubric; ${count(bankCal, (x) => x.gap !== 0)} disagree** (${count(bankCal, (x) => x.gap < 0)} where the rubric scores higher, ${count(bankCal, (x) => x.gap > 0)} where it scores lower). Each disagreement was reviewed individually; the assigned value stands for the reason given.\n\n${table(
      ["Question", "Assigned", "Rubric (score)", "Why the assigned difficulty"],
      bankCal.filter((x) => x.gap !== 0).map((x) => [`${x.b.id} ${x.b.title}`, D(x.b.difficulty), `${D(x.r.difficulty as Difficulty)} (${x.r.score})`, x.b.difficultyWhy]),
    )}\n\nPatterns in the disagreements:\n\n- **Rubric higher than assigned (Medium questions scored Hard):** stacked CTEs plus a window function add many feature points, but these are standard intermediate patterns once each piece is known.\n- **Rubric lower than assigned:** the rubric only sees SQL features. As-of lookups (qb-0043) and interval overlap (qb-0044) are short queries whose difficulty is in the edge cases (half-open intervals, open ends, overlapping bad data), which the rubric cannot see.\n- **Easy questions scored Warm-up:** each has a single construct but a deliberate trap (precedence, an inclusive boundary, case sensitivity), which is what separates Easy from Warm-up.\n`,
  );

  /* ---------- NEW_QUESTIONS.md ---------- */
  const qSections = bankQuestions.map((b) => {
    const ex = examples[b.id];
    const r = rubricFor(b.solution, b.validate?.length ?? 0);
    const validationNotes = [
      b.planValidation ? `**Plan contract:** \`${JSON.stringify(b.planValidation)}\`` : "",
      b.repeatCheck ? "**Replay validation:** the full script runs twice on the same database, for each fixture." : "",
      b.stateQueries?.length ? `**Database-state checks:** ${b.stateQueries.length} full query results compared with an independent reference database.` : "",
      b.equivalent?.length ? `**Equivalent solutions tested:** ${b.equivalent.length}.` : "",
      b.setupSql ? "**Per-question fixture:** Run, Check and table previews include additional setup data; see the machine-readable manifest." : "",
      b.caseStudy ? `**Case study:** ${b.caseStudy.title}, stage ${b.caseStudy.stage}/${b.caseStudy.total}; independently reproducible.` : "",
    ].filter(Boolean).join("\n\n");
    return `### ${b.id} · ${b.title}\n\n- **Difficulty:** ${D(b.difficulty)} — ${b.difficultyWhy} (rubric: ${D(r.difficulty as Difficulty)}, score ${r.score})\n- **Topic:** ${topicLabel[b.primaryTopic]} (\`${b.primaryTopic}\`)${b.topicTags.length ? `; tags ${b.topicTags.map((t) => `\`${t}\``).join(", ")}` : ""}\n- **Dataset:** ${practiceDatasets[b.datasetId].name} · tables ${b.tables.join(", ")} · ${b.mode === "lab" ? "write-enabled lab" : "read-only"}\n- **Objective:** ${b.objective}\n- **Prerequisite lessons:** ${b.prerequisites.map((p) => `${p} (${lessons[p].title})`).join(", ")}\n\n**Task.** ${b.task}\n\n${b.rules.length ? `**Rules.**\n${b.rules.map((x) => `- ${x}`).join("\n")}\n\n` : ""}**Return:** ${b.columns.map((c) => `\`${c}\``).join(", ")} · ${b.ordered ? "row order is checked" : "any row order"}\n\n**Example output** (first ${ex.rows.length} of ${ex.total} rows on the visible data):\n\n${table(ex.columns, ex.rows.map((row) => row.map((v) => (v === null ? "NULL" : String(v)))))}\n\n**Reference solution**\n\n\`\`\`sql\n${b.solution}\n\`\`\`\n\n**Why it works.** ${b.explanation}\n\n**Hints:** ${b.hints.map((h, i) => `(${i + 1}) ${h}`).join(" ")}\n\n${validationNotes}\n\n${b.validate?.length ? `**Object checks:** ${b.validate.length} (${b.validate.map((v) => (v.mustFail ? "write must fail" : v.mustSucceed ? "valid write must succeed" : "state/catalog check")).join(", ")})\n\n` : ""}**Rejected wrong approaches (tested):**\n${b.wrong.map((w) => `- ${w.mistake}`).join("\n")}\n`;
  });
  fs.writeFileSync(
    `${DOCS}/NEW_QUESTIONS.md`,
    `# New question-bank problems (${bankQuestions.length})\n\n${GEN_NOTE}\n\nOriginal problems written for SQL Studio — wording, data and requirements are not taken from any other platform. Every reference solution passes on the visible data and the changed-data fixture; hard-coding the visible output fails; every listed wrong approach is rejected (\`tests/question-bank.test.ts\`, ${bankQuestions.reduce((n, b) => n + b.wrong.length, 0)} wrong answers).\n\n${table(
      ["ID", "Title", "Difficulty", "Topic", "Dataset"],
      bankQuestions.map((b) => [b.id, b.title, D(b.difficulty), topicLabel[b.primaryTopic], b.datasetId]),
    )}\n\n${qSections.join("\n---\n\n")}`,
  );

  /* ---------- PRACTICE_TRACKS.md ---------- */
  const byQ = new Map(all.map((q) => [q.id, q]));
  const inTracks = new Map<string, string[]>();
  for (const t of tracks) for (const id of t.questionIds) inTracks.set(id, [...(inTracks.get(id) ?? []), t.title]);
  const trackIntro = fs.existsSync(`${DOCS}/_tracks.md`) ? fs.readFileSync(`${DOCS}/_tracks.md`, "utf8") : "";
  const trackSections = tracks.map((t, i) => {
    const qs = t.questionIds.map((id) => byQ.get(id)!);
    const problems = trackProblems(t);
    return `## ${String(i + 1).padStart(2, "0")} · ${t.title}\n\n**Objective.** ${t.objective}\n\n**Starting point.** ${t.startingPoint}\n\n**Skills.** ${t.skills.join(" · ")}\n\n**Shape.** ${qs.length} questions · ${DIFFICULTIES.map((d) => `${D(d)} ${count(qs, (q) => q.difficulty === d)}`).join(", ")} · ${new Set(qs.map((q) => q.primaryTopic)).size} topics · ${count(qs, (q) => q.sourceType === "bank")} practice problems + ${count(qs, (q) => q.sourceType !== "bank")} lesson challenges · rule check: ${problems.length ? problems.join("; ") : "passes"}\n\n${table(
      ["#", "Question", "Difficulty", "Topic", "Source", "Also in"],
      qs.map((q, n) => [
        n + 1,
        `${q.id} · ${q.title}`,
        D(q.difficulty),
        topicLabel[q.primaryTopic],
        q.sourceType === "bank" ? "practice problem" : `lesson ${q.sourceLessonId}`,
        (inTracks.get(q.id) ?? []).filter((x) => x !== t.title).join(", "),
      ]),
    )}`;
  });
  fs.writeFileSync(
    `${DOCS}/PRACTICE_TRACKS.md`,
    `# Practice tracks\n\n${GEN_NOTE}\n\n${trackIntro}\n\n## Summary\n\n${table(
      ["Track", "Range", "Questions", "Practice problems", "Lesson challenges", "Topics"],
      tracks.map((t) => {
        const qs = t.questionIds.map((id) => byQ.get(id)!);
        const levels = qs.map((q) => DIFFICULTIES.indexOf(q.difficulty));
        return [t.title, `${D(DIFFICULTIES[Math.min(...levels)])} → ${D(DIFFICULTIES[Math.max(...levels)])}`, qs.length, count(qs, (q) => q.sourceType === "bank"), count(qs, (q) => q.sourceType !== "bank"), new Set(qs.map((q) => q.primaryTopic)).size];
      }),
    )}\n\n${inTracks.size} distinct questions appear in at least one track (${count([...inTracks.keys()], (id) => byQ.get(id)!.sourceType === "bank")} of ${bank.length} practice problems); ${count([...inTracks.values()], (v) => v.length > 1)} appear in two tracks.\n\n${trackSections.join("\n\n")}\n`,
  );

  /* ---------- QUESTION_GAPS.md ---------- */
  const gapsText = fs.existsSync(`${DOCS}/_gaps.md`) ? fs.readFileSync(`${DOCS}/_gaps.md`, "utf8") : "";
  const emptyCells = topicFamilies.flatMap((f) =>
    DIFFICULTIES.filter((d) => count(all, (q) => familyOf(q.primaryTopic) === f.id && q.difficulty === d) === 0).map((d) => `${f.label} × ${D(d)}`),
  );
  fs.writeFileSync(
    `${DOCS}/QUESTION_GAPS.md`,
    `# Question gaps\n\n${GEN_NOTE}\n\n${gapsText}\n\n## Empty topic × difficulty cells (all questions)\n\n${emptyCells.map((c) => `- ${c}`).join("\n") || "None."}\n\nNot every empty cell is a gap: a Warm-up warehouse reconciliation or a Hard SELECT would be artificial.\n`,
  );
  void courseOrder;
});
